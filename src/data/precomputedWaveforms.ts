const waveformCache = new Map<string, WaveformData>();

export function getPrecomputedWaveformForPart(partId: string, audioUrl?: string): WaveformData | null {
  const normId = partId.toLowerCase().trim();
  if (I_HOLD_YOUR_HAND_WAVEFORMS[normId]) {
    return I_HOLD_YOUR_HAND_WAVEFORMS[normId];
  }
  if (audioUrl) {
    const urlLower = audioUrl.toLowerCase();
    if (urlLower.includes('tenor')) return I_HOLD_YOUR_HAND_WAVEFORMS.tenor;
    if (urlLower.includes('lead')) return I_HOLD_YOUR_HAND_WAVEFORMS.lead;
    if (urlLower.includes('bari')) return I_HOLD_YOUR_HAND_WAVEFORMS.baritone;
    if (urlLower.includes('bass')) return I_HOLD_YOUR_HAND_WAVEFORMS.bass;
    if (waveformCache.has(audioUrl)) {
      return waveformCache.get(audioUrl)!;
    }
  }
  return null;
}

export async function fetchAudioWaveform(url: string, numBuckets = 800): Promise<WaveformData | null> {
  if (!url) return null;
  if (waveformCache.has(url)) {
    return waveformCache.get(url)!;
  }
  const pre = getPrecomputedWaveformForPart('', url);
  if (pre) {
    waveformCache.set(url, pre);
    return pre;
  }

  try {
    const response = await fetch(url);
    if (!response.ok) return null;
    const arrayBuffer = await response.arrayBuffer();
    const AudioCtx = window.AudioContext || (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
    const ctx = new AudioCtx();
    const audioBuffer = await ctx.decodeAudioData(arrayBuffer);
    const channelData = audioBuffer.getChannelData(0);
    const totalSamples = channelData.length;
    const samplesPerBucket = totalSamples / numBuckets;
    const peaks: number[] = [];
    const rms: number[] = [];

    let globalPeak = 0;
    let globalRms = 0;
    for (let i = 0; i < totalSamples; i++) {
      const v = Math.abs(channelData[i]);
      if (v > globalPeak) globalPeak = v;
    }

    for (let i = 0; i < numBuckets; i++) {
      const start = Math.floor(i * samplesPerBucket);
      const end = Math.floor((i + 1) * samplesPerBucket);
      let max = 0;
      let sumSq = 0;
      let count = 0;
      for (let j = start; j < end; j++) {
        const val = Math.abs(channelData[j]);
        if (val > max) max = val;
        sumSq += val * val;
        count++;
      }
      const r = count > 0 ? Math.sqrt(sumSq / count) : 0;
      if (r > globalRms) globalRms = r;
      peaks.push(max);
      rms.push(r);
    }

    // Normalize
    const normPeaks: number[] = [];
    const normRms: number[] = [];
    for (let i = 0; i < numBuckets; i++) {
      let p = peaks[i] / (globalPeak || 1);
      let r = rms[i] / (globalRms || 1);
      if (p < 0.035) {
        p = 0;
        r = 0;
      } else {
        p = Number(Math.min(1.0, p).toFixed(3));
        r = Number(Math.min(1.0, r * 0.9).toFixed(3));
      }
      normPeaks.push(p);
      normRms.push(r);
    }

    const result: WaveformData = { peaks: normPeaks, rms: normRms };
    waveformCache.set(url, result);
    ctx.close().catch(() => {});
    return result;
  } catch (err) {
    console.warn('Could not decode audio waveform from URL:', url, err);
    return null;
  }
}
